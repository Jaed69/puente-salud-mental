"""Guardian decision policy and the fixed crisis response.

The crisis response is a fixed script, never generated by a model. ``safe_assess`` fails closed:
any error during assessment is treated as a crisis.
"""

import logging
from typing import Literal

from pydantic import BaseModel, ConfigDict

from puente.guardian import lexicon
from puente.guardian.resources import (
    BOMBEROS_116,
    COMMUNITY_MENTAL_HEALTH_NOTE,
    LINEA_100,
    LINEA_113_SALUD_MENTAL,
    PNP_105,
    SAMU_106,
    CrisisResource,
    ResourceNote,
)

logger = logging.getLogger(__name__)

GUARDIAN_ERROR = "guardian_error"

_SELF_RISK = {
    lexicon.Category.SUICIDAL_IDEATION,
    lexicon.Category.SELF_HARM,
    lexicon.Category.PLAN_OR_MEANS,
}


class GuardDecision(BaseModel):
    model_config = ConfigDict(frozen=True)

    risk: Literal["none", "crisis"]
    categories: tuple[str, ...] = ()


class CrisisResponse(BaseModel):
    model_config = ConfigDict(frozen=True)

    message: str
    resources: tuple[CrisisResource, ...]
    note: ResourceNote


def assess(message: str) -> GuardDecision:
    categories = lexicon.detect(message)
    if not categories:
        return GuardDecision(risk="none")
    return GuardDecision(risk="crisis", categories=tuple(sorted(categories)))


def safe_assess(message: str) -> GuardDecision:
    """Assess a message, failing closed. Never logs the message or the exception text."""
    try:
        return assess(message)
    except Exception as exc:
        logger.error("Guardian assessment failed (%s); failing closed.", type(exc).__name__)
        return GuardDecision(risk="crisis", categories=(GUARDIAN_ERROR,))


_GENERAL_MESSAGE = (
    "Gracias por contármelo. Lo que sientes importa y no tienes que pasar por esto a solas. "
    "Te pido que llames ahora a la Línea 113, opción 5: es gratuita y atiende las 24 horas. "
    "Si estás en peligro inmediato, llama al 106 (SAMU). "
    "Si quieres, sigo aquí contigo mientras buscas ayuda."
)

_VIOLENCE_MESSAGE = (
    "Lo que me cuentas es serio y mereces estar a salvo. "
    "Si estás en peligro ahora, llama al 105 (Policía Nacional). "
    "La Línea 100 te orienta ante situaciones de violencia. "
    "Para apoyo emocional también puedes llamar a la Línea 113, opción 5, gratis y las 24 horas. "
    "Si quieres, sigo aquí contigo."
)


def build_crisis_response(decision: GuardDecision) -> CrisisResponse:
    """Build the fixed crisis script and resource list for a crisis decision."""
    categories = set(decision.categories)
    violence_only = lexicon.Category.VIOLENCE in categories and not categories & _SELF_RISK
    if violence_only:
        message = _VIOLENCE_MESSAGE
        resources = (PNP_105, LINEA_100, LINEA_113_SALUD_MENTAL, SAMU_106, BOMBEROS_116)
    else:
        message = _GENERAL_MESSAGE
        resources = (LINEA_113_SALUD_MENTAL, SAMU_106, PNP_105, LINEA_100, BOMBEROS_116)
    return CrisisResponse(message=message, resources=resources, note=COMMUNITY_MENTAL_HEALTH_NOTE)
